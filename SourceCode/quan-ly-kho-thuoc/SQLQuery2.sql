GO

USE QuanLyKhoThuoc;
GO

CREATE TABLE TAIKHOAN (
    MATAIKHOAN VARCHAR(20) PRIMARY KEY,
    HOTEN NVARCHAR(100) NOT NULL,
    TENDANGNHAP VARCHAR(50) NOT NULL UNIQUE,
    MATKHAU VARCHAR(255) NOT NULL,
    VAITRO NVARCHAR(50) NOT NULL 
);
GO

CREATE TABLE THUOC (
    MATHUOC VARCHAR(20) PRIMARY KEY,
    TENTHUOC NVARCHAR(150) NOT NULL,
    DONVITINH NVARCHAR(20) NOT NULL,
    MANHOM VARCHAR(20),
    MOTA NVARCHAR(255)
);
GO

CREATE TABLE LOTHUOC (
    MALO VARCHAR(20) PRIMARY KEY,
    MATHUOC VARCHAR(20) NOT NULL,
    NGAYSANXUAT DATE,
    NGAYHETHAN DATE NOT NULL,
    NGAYNHAPKHO DATE DEFAULT GETDATE(),
    SOLUONGTON INT NOT NULL CHECK (SOLUONGTON >= 0),
    TRANGTHAI NVARCHAR(30) DEFAULT 'Active', 
    CONSTRAINT FK_LoThuoc_Thuoc FOREIGN KEY (MATHUOC) REFERENCES THUOC(MATHUOC)
);
GO

CREATE TABLE PHIEUDIEUCHINH (
    MAPHIEU VARCHAR(20) PRIMARY KEY,
    NGAYLAP DATETIME DEFAULT GETDATE(),
    NGUOILAPID VARCHAR(20) NOT NULL, 
    NGUOIDUYETID VARCHAR(20),    
    TRANGTHAI NVARCHAR(20) DEFAULT 'Pending', 
    LYDOTUCHOI NVARCHAR(255),
    CONSTRAINT FK_PDC_NguoiLap FOREIGN KEY (NGUOILAPID) REFERENCES TAIKHOAN(MATAIKHOAN),
    CONSTRAINT FK_PDC_NguoiDuyet FOREIGN KEY (NGUOIDUYETID) REFERENCES TAIKHOAN(MATAIKHOAN)
);
GO

CREATE TABLE CHITIETPHIEUDIEUCHINH (
    MACHITIET VARCHAR(20) PRIMARY KEY,
    MAPHIEU VARCHAR(20) NOT NULL,
    MALO VARCHAR(20) NOT NULL,
    SOLUONGTONSOSACH INT NOT NULL,
    SOLUONGTONTHUCTE INT NOT NULL,
    CHENHLECH INT NOT NULL,
    LYDODIEUCHINH NVARCHAR(255),
    CONSTRAINT FK_CTPDC_Phieu FOREIGN KEY (MAPHIEU) REFERENCES PHIEUDIEUCHINH(MAPHIEU),
    CONSTRAINT FK_CTPDC_LoThuoc FOREIGN KEY (MALO) REFERENCES LOTHUOC(MALO)
);
GO

CREATE TABLE PHIEUXUAT (
    MAPHIEUXUAT VARCHAR(20) PRIMARY KEY,
    NGAYXUAT DATETIME DEFAULT GETDATE(),
    MATAIKHOAN VARCHAR(20) NOT NULL,
    GHICHU NVARCHAR(255),
    CONSTRAINT FK_PhieuXuat_TaiKhoan FOREIGN KEY (MATAIKHOAN) REFERENCES TAIKHOAN(MATAIKHOAN)
);
GO

CREATE TABLE CHITIETPHIEUXUAT (
    MACTPX VARCHAR(20) PRIMARY KEY,
    MAPHIEUXUAT VARCHAR(20) NOT NULL,
    MALO VARCHAR(20) NOT NULL,
    SOLUONGXUAT INT NOT NULL CHECK (SOLUONGXUAT > 0),
    CONSTRAINT FK_CTPX_PhieuXuat FOREIGN KEY (MAPHIEUXUAT) REFERENCES PHIEUXUAT(MAPHIEUXUAT),
    CONSTRAINT FK_CTPX_LoThuoc FOREIGN KEY (MALO) REFERENCES LOTHUOC(MALO)
);
GO

CREATE TABLE NHATKYHOATDONG (
    MALOG VARCHAR(20) PRIMARY KEY,
    MATAIKHOAN VARCHAR(20) NOT NULL,
    HANHDONG NVARCHAR(100) NOT NULL,
    DOITUONGTACDONG NVARCHAR(100) NOT NULL,
    THOIGIAN DATETIME DEFAULT GETDATE(),
    CHITIET NVARCHAR(MAX),
    CONSTRAINT FK_NhatKy_TaiKhoan FOREIGN KEY (MATAIKHOAN) REFERENCES TAIKHOAN(MATAIKHOAN)
);
GO


